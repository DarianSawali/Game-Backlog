import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import AppStateBoundary from "@/components/auth/AppStateBoundary";
import AppStateProvider from "@/components/auth/AppStateProvider";
import { getDevelopmentAuth } from "@/lib/development-auth";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const developmentAuth = await getDevelopmentAuth();

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <AppStateProvider
          initialAuthState={developmentAuth.initialAuthState}
          developmentUser={developmentAuth.developmentUser}
          developmentControlsEnabled={developmentAuth.developmentControlsEnabled}
        >
          <AppStateBoundary>{children}</AppStateBoundary>
        </AppStateProvider>
      </body>
    </html>
  );
}
